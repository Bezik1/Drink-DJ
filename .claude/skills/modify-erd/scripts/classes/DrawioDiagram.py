import hashlib
import html
import json
import xml.etree.ElementTree as ET

from const.general import FONT_SIZES, GENERATOR, PREVIOUS_GENERATORS, STYLES


class DrawioDiagram:
    """
    draw.io representation of the Chen layout.

    Args:
        layout (ChenLayout): Positioned layout.
    """

    def __init__(self, layout):
        self.layout = layout

    def __call__(self):
        """
        Builds the graph. Lines are drawn first, so they stay under the shapes.

        Returns:
            Element: mxGraphModel element.
        """
        self.model = ET.Element("mxGraphModel", {
            "grid": "0",
            "page": "1",
            "pageScale": "1",
            "pageWidth": str(self.layout.width),
            "pageHeight": str(self.layout.height),
        })
        self.root = ET.SubElement(self.model, "root")

        ET.SubElement(self.root, "mxCell", {"id": "0"})
        ET.SubElement(self.root, "mxCell", {"id": "1", "parent": "0"})

        shapes = [shape for shape in self.layout.shapes if shape.kind != "cardinality"]
        ids = {shape: f"s{index}" for index, shape in enumerate(shapes)}

        self.build_lines(ids)
        self.build_shapes(shapes, ids)

        return self.model

    def build_lines(self, ids):
        for index, line in enumerate(self.layout.lines):
            edge = ET.SubElement(self.root, "mxCell", {
                "id": f"l{index}",
                "style": self.line_style(line),
                "edge": "1",
                "parent": "1",
                "source": ids[line.source],
                "target": ids[line.target],
            })
            geometry = ET.SubElement(edge, "mxGeometry", {"relative": "1", "as": "geometry"})

            if line.control is not None:
                points = ET.SubElement(geometry, "Array", {"as": "points"})
                ET.SubElement(points, "mxPoint", {
                    "x": str(round(line.control[0])),
                    "y": str(round(line.control[1])),
                })

            if line.label is None:
                continue

            label = ET.SubElement(self.root, "mxCell", {
                "id": f"c{index}",
                "value": html.escape(line.cardinality),
                "style": f"{STYLES['cardinality']}fontSize={FONT_SIZES['cardinality']};",
                "vertex": "1",
                "connectable": "0",
                "parent": f"l{index}",
            })
            geometry = ET.SubElement(label, "mxGeometry", {
                "x": f"{line.label_position:.2f}",
                "relative": "1",
                "as": "geometry",
            })
            ET.SubElement(geometry, "mxPoint", {
                "x": str(round(line.label_offset[0])),
                "y": str(round(line.label_offset[1])),
                "as": "offset",
            })

    def line_style(self, line):
        """
        A curve is fixed to the ends of the straight line, because draw.io
        would otherwise aim both ends at the control point.

        Args:
            line (Line): Line of the layout.

        Returns:
            str: Style of the edge.
        """
        if line.control is None:
            return STYLES["line"]

        exit_x, exit_y = line.port(line.source, line.start)
        entry_x, entry_y = line.port(line.target, line.end)

        return (
            f"{STYLES['curve']}exitX={exit_x:.4f};exitY={exit_y:.4f};exitPerimeter=1;"
            f"entryX={entry_x:.4f};entryY={entry_y:.4f};entryPerimeter=1;"
        )

    def build_shapes(self, shapes, ids):
        for shape in shapes:
            value = html.escape(shape.text).replace("\n", "<br>")

            if shape.partial:
                value = f'<span style="border-bottom:2px dashed #000000">{value}</span>'

            cell = ET.SubElement(self.root, "mxCell", {
                "id": ids[shape],
                "value": value,
                "style": f"{STYLES[shape.style]}fontSize={FONT_SIZES[shape.kind]};",
                "vertex": "1",
                "parent": "1",
            })
            left, top, _, _ = shape.box()

            ET.SubElement(cell, "mxGeometry", {
                "x": str(round(left)),
                "y": str(round(top)),
                "width": str(round(shape.width)),
                "height": str(round(shape.height)),
                "as": "geometry",
            })


def fingerprint(model):
    cells = [[element.tag, sorted(element.attrib.items())] for element in model.iter()]

    return hashlib.sha256(json.dumps(cells).encode("utf-8")).hexdigest()


def is_unchanged(path):
    """
    Checks, whether a file was generated by the skill and not edited later.

    Args:
        path (Path): Path of the draw.io file.

    Returns:
        bool: True, if the file can be safely generated again.
    """
    try:
        file = ET.parse(path).getroot()
    except ET.ParseError:
        return False

    model = file.find("diagram/mxGraphModel")

    return (
        file.get("host") in (GENERATOR, *PREVIOUS_GENERATORS) and
        model is not None and
        file.get("etag") == fingerprint(model)
    )


def read_page_size(path):
    """
    Reads the page of a saved diagram, which includes its padding.

    Args:
        path (Path): Path of the draw.io file.

    Returns:
        float[2]: Width and height of the page in pixels.

    Raises:
        RuntimeError: The file has no readable page.
    """
    model = ET.parse(path).getroot().find("diagram/mxGraphModel")

    if model is None or not model.get("pageWidth") or not model.get("pageHeight"):
        raise RuntimeError(f"The page of {path} cannot be read. Save the diagram again.")

    return float(model.get("pageWidth")), float(model.get("pageHeight"))


def save_diagram(model, path, name):
    file = ET.Element("mxfile", {"host": GENERATOR, "etag": fingerprint(model)})
    diagram = ET.SubElement(file, "diagram", {"id": name, "name": name})
    diagram.append(model)

    content = ET.tostring(file, encoding="unicode").replace("><mxCell", ">\n<mxCell")

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(f"{content}\n".encode("utf-8"))
