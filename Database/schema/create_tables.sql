--
-- Title:        Extensions
-- Description:  pgcrypto makes the bcrypt hashes of the passwords, pg_trgm makes the
--               search by a part of the name fast.
-- Requirements: NFR02, NFR09
-- Constraints:  -
--
CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS pg_trgm;


--
-- Title:        Flavour_Preferences
-- Description:  Wanted flavour of a User or of a Drink Version: nine levels from 0 to 20.
-- Requirements: R26, R27, R28, R29
-- Constraints:  C06
--
CREATE TABLE Flavour_Preferences (
    identifier  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    sweetness   INTEGER NOT NULL DEFAULT 10,
    sourness    INTEGER NOT NULL DEFAULT 10,
    spiciness   INTEGER NOT NULL DEFAULT 10,
    bitterness  INTEGER NOT NULL DEFAULT 10,
    fruitiness  INTEGER NOT NULL DEFAULT 10,
    herbalness  INTEGER NOT NULL DEFAULT 10,
    smokiness   INTEGER NOT NULL DEFAULT 10,
    fizziness   INTEGER NOT NULL DEFAULT 10,
    intensity   INTEGER NOT NULL DEFAULT 10,

    CONSTRAINT flavour_preferences_pk PRIMARY KEY (identifier),
    CONSTRAINT flavour_preferences_levels_range CHECK (
        sweetness  BETWEEN 0 AND 20 AND
        sourness   BETWEEN 0 AND 20 AND
        spiciness  BETWEEN 0 AND 20 AND
        bitterness BETWEEN 0 AND 20 AND
        fruitiness BETWEEN 0 AND 20 AND
        herbalness BETWEEN 0 AND 20 AND
        smokiness  BETWEEN 0 AND 20 AND
        fizziness  BETWEEN 0 AND 20 AND
        intensity  BETWEEN 0 AND 20
    )
);


--
-- Title:        User
-- Description:  Account of a person. "User" is quoted, because it is a reserved word in
--               SQL.
-- Requirements: R01, R02, R03, R27, NFR02
-- Constraints:  C12, C13, C20, C26
--
CREATE TABLE "User" (
    username                       VARCHAR(50)  NOT NULL,
    email                          VARCHAR(254) NOT NULL,
    password                       VARCHAR(255) NOT NULL,
    profile_image                  VARCHAR(255) NULL,
    date_of_account_creation       DATE         NOT NULL DEFAULT CURRENT_DATE,
    flavour_preferences_identifier INTEGER      NOT NULL,

    CONSTRAINT user_pk PRIMARY KEY (username),
    CONSTRAINT user_username_not_blank CHECK (btrim(username) <> ''),
    CONSTRAINT user_email_format CHECK (email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
    CONSTRAINT user_password_bcrypt CHECK (password ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$'),
    CONSTRAINT user_flavour_preferences_unique UNIQUE (flavour_preferences_identifier),
    CONSTRAINT user_flavour_preferences_fk FOREIGN KEY (flavour_preferences_identifier)
        REFERENCES Flavour_Preferences (identifier) ON DELETE NO ACTION
);


--
-- Title:        user_email_unique
-- Description:  The e-mail is unique without regard to letter case.
-- Requirements: R02
-- Constraints:  C09
--
CREATE UNIQUE INDEX user_email_unique ON "User" (lower(email));


--
-- Title:        Passkey
-- Description:  Face ID passkeys of a User.
-- Requirements: R04, R05, R47, NFR03
-- Constraints:  C37
--
CREATE TABLE Passkey (
    credential_identifier VARCHAR(255)  NOT NULL,
    public_key            VARCHAR(1000) NOT NULL,
    date_of_creation      DATE          NOT NULL DEFAULT CURRENT_DATE,
    username              VARCHAR(50)   NOT NULL,

    CONSTRAINT passkey_pk PRIMARY KEY (credential_identifier),
    CONSTRAINT passkey_user_fk FOREIGN KEY (username)
        REFERENCES "User" (username) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT passkey_public_key_only CHECK (public_key !~* 'PRIVATE KEY')
);


--
-- Title:        Drink
-- Description:  A Drink with its statistics. popularity and average_rating are calculated
--               by the database.
-- Requirements: R07, R14, R34, R35
-- Constraints:  C01, C17, C27, C28
--
CREATE TABLE Drink (
    identifier       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name             VARCHAR(100)  NOT NULL,
    description      VARCHAR(1000) NOT NULL,
    photo            VARCHAR(255)  NULL,
    date_of_creation DATE          NOT NULL DEFAULT CURRENT_DATE,
    base_spirit      VARCHAR(20)   NULL,
    popularity       DECIMAL(10,2) NOT NULL DEFAULT 0,
    average_rating   DECIMAL(10,2) NOT NULL DEFAULT 0,

    CONSTRAINT drink_pk PRIMARY KEY (identifier),
    CONSTRAINT drink_base_spirit_domain
        CHECK (base_spirit IN ('vodka', 'gin', 'rum', 'tequila', 'whisky')),
    CONSTRAINT drink_popularity_not_negative CHECK (popularity >= 0),
    CONSTRAINT drink_average_rating_range CHECK (average_rating BETWEEN 0 AND 5)
);


--
-- Title:        Drink_Version
-- Description:  A saved version of a Drink. The totals, the flavour distribution and the
--               estimated match are calculated by the database.
-- Requirements: R08, R09, R10, R11, R12, R15, R21, R22, R24, R25, R28
-- Constraints:  C10, C11, C13, C14, C15, C16, C20, C29, C30, C32, C34, C35, C36
--
CREATE TABLE Drink_Version (
    drink_version_id               INTEGER GENERATED BY DEFAULT AS IDENTITY,
    version_number                 INTEGER       NOT NULL,
    name                           VARCHAR(100)  NOT NULL,
    branch                         VARCHAR(100)  NOT NULL DEFAULT 'main',
    message                        VARCHAR(255)  NULL,
    date_of_creation               DATE          NOT NULL DEFAULT CURRENT_DATE,
    total_volume                   DECIMAL(10,2) NOT NULL DEFAULT 0,
    total_alcohol_percentage       DECIMAL(10,2) NOT NULL DEFAULT 0,
    flavour_distribution           VARCHAR(255)  NOT NULL
        DEFAULT '{"sour": 0, "sweet": 0, "bitter": 0, "strong": 0}',
    estimated_match                INTEGER       NOT NULL DEFAULT 0,
    drink_identifier               INTEGER       NOT NULL,
    author_username                VARCHAR(50)   NULL,
    flavour_preferences_identifier INTEGER       NOT NULL,
    base_drink_version_id          INTEGER       NULL,

    CONSTRAINT drink_version_pk PRIMARY KEY (drink_version_id),
    CONSTRAINT drink_version_natural_key UNIQUE (drink_identifier, version_number),
    CONSTRAINT drink_version_drink_fk FOREIGN KEY (drink_identifier)
        REFERENCES Drink (identifier) ON DELETE CASCADE,
    CONSTRAINT drink_version_number_positive CHECK (version_number >= 1),
    CONSTRAINT drink_version_branch_not_blank CHECK (btrim(branch) <> ''),
    CONSTRAINT drink_version_base_fk FOREIGN KEY (base_drink_version_id)
        REFERENCES Drink_Version (drink_version_id) ON DELETE SET NULL,
    CONSTRAINT drink_version_author_fk FOREIGN KEY (author_username)
        REFERENCES "User" (username) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT drink_version_flavour_preferences_unique UNIQUE (flavour_preferences_identifier),
    CONSTRAINT drink_version_flavour_preferences_fk FOREIGN KEY (flavour_preferences_identifier)
        REFERENCES Flavour_Preferences (identifier) ON DELETE NO ACTION,
    CONSTRAINT drink_version_total_volume_not_negative CHECK (total_volume >= 0),
    CONSTRAINT drink_version_alcohol_range CHECK (total_alcohol_percentage BETWEEN 0 AND 100),
    CONSTRAINT drink_version_estimated_match_range CHECK (estimated_match BETWEEN 0 AND 100)
);


--
-- Title:        Ingredient
-- Description:  A spirit or an addition with its alcohol percentage.
-- Requirements: R17, R18
-- Constraints:  C03, C05
--
CREATE TABLE Ingredient (
    name               VARCHAR(100)  NOT NULL,
    category           VARCHAR(20)   NOT NULL,
    alcohol_percentage DECIMAL(10,2) NOT NULL DEFAULT 0,

    CONSTRAINT ingredient_pk PRIMARY KEY (name),
    CONSTRAINT ingredient_category_domain CHECK (category IN ('alcohol', 'addition')),
    CONSTRAINT ingredient_alcohol_range CHECK (alcohol_percentage BETWEEN 0 AND 100)
);


--
-- Title:        ingredient_name_unique
-- Description:  The name is unique without regard to letter case.
-- Requirements: R18
-- Constraints:  -
--
CREATE UNIQUE INDEX ingredient_name_unique ON Ingredient (lower(name));


--
-- Title:        Version_Ingredient
-- Description:  Ingredients of a Drink Version with their amounts and units.
-- Requirements: R19, R20
-- Constraints:  C08, C40
--
CREATE TABLE Version_Ingredient (
    drink_version_id INTEGER       NOT NULL,
    ingredient_name  VARCHAR(100)  NOT NULL,
    amount           DECIMAL(10,2) NOT NULL,
    unit             VARCHAR(20)   NOT NULL,

    CONSTRAINT version_ingredient_pk PRIMARY KEY (drink_version_id, ingredient_name),
    CONSTRAINT version_ingredient_drink_version_fk FOREIGN KEY (drink_version_id)
        REFERENCES Drink_Version (drink_version_id) ON DELETE CASCADE,
    CONSTRAINT version_ingredient_ingredient_fk FOREIGN KEY (ingredient_name)
        REFERENCES Ingredient (name) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT version_ingredient_amount_positive CHECK (amount > 0),
    CONSTRAINT version_ingredient_unit_domain CHECK (
        unit IN ('ml', 'cl', 'oz', 'tsp', 'tbsp', 'dashes', 'leaves', 'pieces', 'portion')
    )
);


--
-- Title:        Review
-- Description:  A Review of a Drink Version. A perception, that is not given, is
--               not_rated, and the notes are optional.
-- Requirements: R30, R31, R32, R33, R47
-- Constraints:  C04, C07, C13, C39
--
CREATE TABLE Review (
    identifier            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    number_of_stars       INTEGER       NOT NULL,
    notes                 VARCHAR(1000) NULL,
    date_of_creation      DATE          NOT NULL DEFAULT CURRENT_DATE,
    sweetness_perception  VARCHAR(20)   NOT NULL DEFAULT 'not_rated',
    sourness_perception   VARCHAR(20)   NOT NULL DEFAULT 'not_rated',
    bitterness_perception VARCHAR(20)   NOT NULL DEFAULT 'not_rated',
    strength_perception   VARCHAR(20)   NOT NULL DEFAULT 'not_rated',
    drink_version_id      INTEGER       NOT NULL,
    username              VARCHAR(50)   NOT NULL,

    CONSTRAINT review_pk PRIMARY KEY (identifier),
    CONSTRAINT review_drink_version_fk FOREIGN KEY (drink_version_id)
        REFERENCES Drink_Version (drink_version_id) ON DELETE CASCADE,
    CONSTRAINT review_user_fk FOREIGN KEY (username)
        REFERENCES "User" (username) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT review_stars_range CHECK (number_of_stars BETWEEN 1 AND 5),
    CONSTRAINT review_perception_domain CHECK (
        sweetness_perception  IN ('not_rated', 'too_little', 'just_right', 'too_much') AND
        sourness_perception   IN ('not_rated', 'too_little', 'just_right', 'too_much') AND
        bitterness_perception IN ('not_rated', 'too_little', 'just_right', 'too_much') AND
        strength_perception   IN ('not_rated', 'too_little', 'just_right', 'too_much')
    )
);


--
-- Title:        Liked_Ingredient
-- Description:  Ingredients liked by a User, also the spirits.
-- Requirements: R36, R47
-- Constraints:  C41
--
CREATE TABLE Liked_Ingredient (
    username        VARCHAR(50)  NOT NULL,
    ingredient_name VARCHAR(100) NOT NULL,

    CONSTRAINT liked_ingredient_pk PRIMARY KEY (username, ingredient_name),
    CONSTRAINT liked_ingredient_user_fk FOREIGN KEY (username)
        REFERENCES "User" (username) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT liked_ingredient_ingredient_fk FOREIGN KEY (ingredient_name)
        REFERENCES Ingredient (name) ON DELETE CASCADE ON UPDATE CASCADE
);


--
-- Title:        Album
-- Description:  An Album of Drinks. It is private by default, and the icon and the photo
--               are optional.
-- Requirements: R37, R38, R39, R40, R43, R45, R47
-- Constraints:  C02, C13, C33, C38
--
CREATE TABLE Album (
    identifier       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name             VARCHAR(100) NOT NULL,
    icon             VARCHAR(255) NULL,
    photo            VARCHAR(255) NULL,
    kind             VARCHAR(20)  NOT NULL DEFAULT 'custom',
    public_status    BOOLEAN      NOT NULL DEFAULT FALSE,
    date_of_creation DATE         NOT NULL DEFAULT CURRENT_DATE,
    number_of_drinks INTEGER      NOT NULL DEFAULT 0,
    username         VARCHAR(50)  NOT NULL,

    CONSTRAINT album_pk PRIMARY KEY (identifier),
    CONSTRAINT album_user_fk FOREIGN KEY (username)
        REFERENCES "User" (username) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT album_kind_domain
        CHECK (kind IN ('favourites', 'to_check_out', 'your_drinks', 'custom')),
    CONSTRAINT album_number_of_drinks_not_negative CHECK (number_of_drinks >= 0)
);


--
-- Title:        album_one_system_album_per_kind
-- Description:  Each User has only one favourites, to_check_out and your_drinks Album.
-- Requirements: R39
-- Constraints:  C21
--
CREATE UNIQUE INDEX album_one_system_album_per_kind
    ON Album (username, kind) WHERE kind <> 'custom';


--
-- Title:        Album_Entry
-- Description:  Drinks of an Album with the date of adding.
-- Requirements: R41, R42
-- Constraints:  C42
--
CREATE TABLE Album_Entry (
    album_identifier INTEGER NOT NULL,
    drink_identifier INTEGER NOT NULL,
    date_of_adding   DATE    NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT album_entry_pk PRIMARY KEY (album_identifier, drink_identifier),
    CONSTRAINT album_entry_album_fk FOREIGN KEY (album_identifier)
        REFERENCES Album (identifier) ON DELETE CASCADE,
    CONSTRAINT album_entry_drink_fk FOREIGN KEY (drink_identifier)
        REFERENCES Drink (identifier) ON DELETE CASCADE
);


--
-- Title:        Foreign key indexes
-- Description:  An index on every foreign key, for fast joins and deletes.
-- Requirements: NFR09
-- Constraints:  -
--
CREATE INDEX passkey_username_idx        ON Passkey (username);
CREATE INDEX drink_version_drink_idx     ON Drink_Version (drink_identifier, branch, version_number);
CREATE INDEX drink_version_author_idx    ON Drink_Version (author_username);
CREATE INDEX drink_version_base_idx      ON Drink_Version (base_drink_version_id);
CREATE INDEX version_ingredient_name_idx ON Version_Ingredient (ingredient_name);
CREATE INDEX review_drink_version_idx    ON Review (drink_version_id);
CREATE INDEX review_username_idx         ON Review (username);
CREATE INDEX liked_ingredient_name_idx   ON Liked_Ingredient (ingredient_name);
CREATE INDEX album_username_idx          ON Album (username);
CREATE INDEX album_entry_drink_idx       ON Album_Entry (drink_identifier);


--
-- Title:        Library indexes
-- Description:  Filtering of the Library by base spirit and sorting by popularity or
--               rating.
-- Requirements: NFR09
-- Constraints:  -
--
CREATE INDEX drink_base_spirit_idx       ON Drink (base_spirit);
CREATE INDEX drink_popularity_idx        ON Drink (popularity DESC);
CREATE INDEX drink_average_rating_idx    ON Drink (average_rating DESC);


--
-- Title:        Search indexes
-- Description:  Trigram indexes for the search by a part of the name.
-- Requirements: NFR09
-- Constraints:  -
--
CREATE INDEX drink_name_trgm_idx         ON Drink USING gin (lower(name) gin_trgm_ops);
CREATE INDEX ingredient_name_trgm_idx    ON Ingredient USING gin (lower(name) gin_trgm_ops);
